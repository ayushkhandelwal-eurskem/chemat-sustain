// Dependency-free runner using the repository's installed TypeScript compiler.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const ts = require('typescript');
function load(relative) {
  const file = path.resolve(__dirname, '..', relative);
  const code = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText;
  const mod = { exports: {} };
  new Function('require', 'module', 'exports', code)(name => require(path.resolve(path.dirname(file), name)), mod, mod.exports);
  return mod.exports;
}
const recognition = load('src/lib/scientificRecognition.ts');
const images = load('src/lib/images/testImageConfig.tsx');
const source = (rows) => ({sheet_name: 'Fixture', rows, merged_ranges: []});
const row = (number, values) => ({row: number, cells: Object.entries(values).map(([column, value]) => ({column, coordinate: `${column}${number}`, value}))});
const conditions = source([
  row(1, {A:'Treatment concentration series labels', B:'Sample 1', C:'Sample 2'}),
  row(2, {A:'Treatment concentration series identifications', B:'CTRL', C:' VEHICLE '}),
  row(3, {A:'Abbreviation:', B:'IL-6'}), row(4, {A:'Housekeeping gene (HKG):', B:'GAPDH'}),
]);
const context = recognition.scientificContext(conditions);
assert.deepEqual(context.samples, {'Sample 1':'CTRL', 'Sample 2':'VEHICLE'});
assert.deepEqual(context.normalization, [{target:'IL-6', reference:'GAPDH'}]);
const measurements = [{endpoint:'IL-6', treatment:'Sample 1', value:null, unit:'Ct', source_cell:'Raw!D8', replication:'R1'}, {endpoint:'GAPDH', treatment:'Sample 2', value:0, unit:'Ct', source_cell:'Raw!E8', replication:'R1'}];
const groups = recognition.groupMeasurements(measurements, 'raw', context);
assert.equal(groups[0].rows[0][3], null);
assert.equal(groups[1].rows[0][3], 0);
assert.match(groups[1].title, /Reference gene/);
const unknown = source([row(1, {A:'Unknown header', B:0}), row(2, {A:'Unknown method', B:null})]);
assert.equal(recognition.groupStatistics(unknown).flatMap(g => g.source.rows.flatMap(r => r.cells)).length, 4);
assert.equal(images.normalizeCmsId('CMS_1c_AuNP'), '1c');
assert.equal(images.isValidCmsId('CMS_1c_AuNP'), true);
assert.equal(images.resolveScientificImages('WP3', '1c', 'annx', 'final').length, 0);
assert(images.resolveScientificImages('WP2', '15a', 'sims').length > 0);
for (const img of images.resolveScientificImages('WP2', '15a', 'sims')) assert(fs.existsSync(path.join(__dirname, '../public', decodeURIComponent(img.url))));
console.log('PASS recognition fixtures: explicit mappings, null/zero, unknown-statistics fallback, verified image paths and identity isolation');

// Optional private workbook payloads, generated by the existing Python parsers.
for (const file of process.argv.slice(2)) {
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  const finals = data.final_results.measurements;
  const context = recognition.scientificContext(data.test_details.source, finals);
  for (const [category, blocks] of [['raw', data.replications], ['processed', data.processed_data.blocks], ['final', [{measurements:finals}]]]) {
    for (const block of blocks) {
      const grouped = recognition.groupMeasurements(block.measurements, category, context);
      assert.equal(grouped.flatMap(g => g.rows).length, block.measurements.length);
      const expected = block.measurements.map(m => [m.source_cell,m.value,m.unit,m.replication ?? null]).sort();
      const actual = grouped.flatMap(g => g.rows.map(r => [r[7],r[3],r[4],r[2] === 'Mean (reported)' ? null : r[2]])).sort();
      assert.deepEqual(actual, expected);
      if (block.records) {
        const flow = recognition.groupFlowRecords(block.records, block.source, context);
        const count = block.records.reduce((n, r) => n + Object.keys(r).filter(k => !['sample','gate','source_row'].includes(k)).length, 0);
        assert.equal(flow.flatMap(g => g.rows).length, count);
      }
    }
  }
  const source = data.statistical_analysis.source;
  const stats = recognition.groupStatistics(source, finals.map(m => m.endpoint));
  const original = source.rows.flatMap(r => r.cells.map(c => JSON.stringify(c))).sort();
  const categorized = stats.flatMap(g => g.source.rows.flatMap(r => r.cells.map(c => JSON.stringify(c)))).sort();
  assert.deepEqual(categorized, original, 'All statistical source values/formulas retained exactly once');
  const endpoints = [...new Set(finals.map(m => m.endpoint))];
  for (const endpoint of endpoints) assert(stats.some(g => g.endpoint === endpoint), `Missing statistical endpoint ${endpoint}`);
  if (endpoints.includes('IL-6')) {
    const anova = stats.find(g => g.endpoint === 'IL-6' && g.title.endsWith('ANOVA summary'));
    assert(anova);
    assert.equal(anova.source.rows.find(r => r.row === 16).cells.find(c => c.column === 'B').value, source.rows.find(r => r.row === 16).cells.find(c => c.column === 'B').value);
    assert(!anova.source.rows.flatMap(r => r.cells).some(c => ['L','M','V','W'].includes(c.column)), 'No other gene statistics in IL-6 panel');
  }
  if (context.references.length) assert.equal(context.samples['Sample 1'], 'CTRL');
  console.log(`PASS ${path.basename(file)}: all raw/processed/final measurements preserved; ${stats.length} statistical groups; endpoints: ${endpoints.join(', ')}`);
}